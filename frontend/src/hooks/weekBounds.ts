/**
 * Границы листания недель на экране статистики.
 *
 * Единственная осмысленная граница — «не в будущее»: статистики за ещё не
 * наступившие недели не существует.
 *
 * Назад листать можно свободно. Нижней границей когда-то была неделя самого
 * раннего AI-отчёта, и это была ошибка: экран показывает СТАТИСТИКУ, а отчёт —
 * лишь один блок внутри неё. При единственном отчёте за текущую неделю кнопка
 * «назад» гасла, хотя задачи в базе были на два месяца раньше. Неделя без
 * данных показывает нули — это честно и понятно само по себе.
 */

/** Назад — всегда. Аргумент оставлен для симметрии вызова. */
export function canPageBack(_weekStart: string): boolean {
  return true
}

/** Вперёд — пока выбранная неделя строго раньше текущей. */
export function canPageForward(weekStart: string, currentMonday: string): boolean {
  return weekStart < currentMonday
}
