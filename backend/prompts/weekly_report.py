"""
Промпт для еженедельного AI-отчёта.

Редактируй этот файл, чтобы изменить структуру, тон и формат отчёта.
Данные (WeeklyData) собираются в app/services/weekly_report.py — там не трогай.
"""
from app.services.weekly_report_prompt import WeeklyData


def build_prompt(data: WeeklyData) -> str:
    # ── Оценка для примеров в формате ──
    if data.overall_rate >= 70:
        rate_label = "хороший результат"
    elif data.overall_rate >= 40:
        rate_label = "средний результат"
    else:
        rate_label = "низкий результат"

    if data.overall_rate < 40:
        tone = (
            "говори прямо и жёстко, но без занудства — "
            "как друг, которому надоело смотреть на повторяющиеся ошибки."
        )
    elif data.overall_rate < 70:
        tone = (
            "смешай честную критику с признанием того, что получилось — "
            "не хвали огульно, но и не дави."
        )
    else:
        tone = (
            "искренняя радость за результат, но сразу укажи на слабое место — "
            "чтобы не расслаблялся."
        )

    # «Без проекта» — виртуальный бакет для задач без доски, это не настоящий
    # проект, называть его в отчёте по имени нельзя.
    DEFAULT_BUCKET = "Без проекта"
    real_projects = [p for p in data.projects if p.name != DEFAULT_BUCKET]

    # ── Лучший и худший проект (только реальные, без бакета) ──
    if real_projects:
        best = max(real_projects, key=lambda p: p.completion_rate)
        worst = min(real_projects, key=lambda p: p.completion_rate)
    else:
        best = worst = None

    # Примеры имён для живых образцов — подставляем реальные данные,
    # чтобы слабая LLM не копировала шаблон с квадратными скобками.
    example_project = (
        worst.name if worst else (best.name if best else "один из проектов")
    )
    example_habit = data.habits[0].name if data.habits else "привычка"
    example_habit_pct = data.habits[0].pct if data.habits else 0

    lines: list[str] = []

    # ── РОЛЬ ──
    lines += [
        "Ты — близкий друг и наставник пользователя, который искренне заинтересован в его росте.",
        "Ты знаешь его задачи и привычки за эту неделю — они перечислены ниже.",
        "Твоя задача: написать еженедельный разбор так, как будто вы сидите за кофе и ты честно,",
        "но по-человечески говоришь ему, как прошла неделя. Не как робот, не как корпоративный отчёт.",
        "",
    ]

    # ── ЖЁСТКИЕ ПРАВИЛА ──
    lines += [
        "━━━ ПРАВИЛА (нарушение любого = неприемлемый ответ) ━━━",
        "",
        "★ САМОЕ ВАЖНОЕ ★",
        "Твой ответ ДОЛЖЕН содержать ВСЕ СЕМЬ разделов ниже, именно в этом порядке:",
        "  1) ## Вступление",
        "  2) ## Оценка недели",
        "  3) ## Разбор по проектам",
        "  4) ## Выполненные задачи",
        "  5) ## Провалы недели",
        "  6) ## 3 совета на следующую неделю",
        "  7) ## Итог",
        "Отсутствие любого из этих разделов = полностью неприемлемый ответ.",
        "Не останавливайся после вступления. Пройди все 7 разделов до конца.",
        "Минимальный объём ответа — 400 слов. Короткий ответ = неприемлемый.",
        "",
        f"Тон для этой недели: {tone}",
        "Пиши от первого лица, обращайся на «ты».",
        "",
        "1. Каждое утверждение должно содержать цифру или название задачи/привычки из данных.",
        "2. Если данных нет — пиши «данных нет», не выдумывай.",
        "3. Советы должны ссылаться на конкретные задачи, проекты или привычки из данных.",
        "4. Markdown-структура ОБЯЗАТЕЛЬНА в каждой секции. Недостаточно голых абзацев.",
        "   Текст рендерится с подсветкой жирного и буллетов — выжимай из этого максимум.",
        "5. ЖИРНЫЙ `**...**` ОБЯЗАТЕЛЕН для трёх категорий:",
        "   (a) все числа и проценты: **12**, **63%**, **3/7**, **0 из 5**;",
        "   (b) названия проектов в кавычках: **«Проект X»**;",
        "   (c) ключевые названия задач и привычек: **«Написать отчёт»**, **«бег»**.",
        "   Плоский текст без жирных акцентов = неприемлемый ответ.",
        "6. В каждой секции минимум один буллет-список (кроме «Итог», где можно цитатой `>`).",
        "   «Вступление»: 2–3 короткие фразы + буллеты с наблюдениями.",
        "   «Оценка недели»: начни с буллет-списка ключевых метрик (выполнено, просрочено, %),",
        "     потом 2–3 предложения интерпретации.",
        "   «Разбор по проектам»: по каждому проекту — `### «Имя»` + буллеты с показателями,",
        "     затем 1–2 предложения вывода.",
        "   «Выполненные» и «Провалы»: только списки, без вступительных абзацев.",
        "   «3 совета»: ровно три пункта нумерованным списком, каждый — одно действие.",
        "   «Итог»: 1–2 фразы + цитата `>` с главным выводом недели.",
        "7. Не повторяй сырые данные — интерпретируй их.",
        "8. ЗАПРЕЩЕНЫ фразы: «не тот результат, которого я от тебя жду», «не те результаты»,",
        "   «ожидал большего», «можно лучше», «старался», «продолжай в том же духе»,",
        "   «молодец», «неплохо», «в целом».",
        "9. КРИТИЧНО: в ответе НЕ должно быть текста в квадратных скобках [...].",
        "   Примеры ниже — это образцы СТИЛЯ, а не шаблоны для заполнения.",
        "10. Не копируй примеры дословно — бери стиль и переписывай своими словами,",
        "    используя реальные названия проектов и цифры из секции ДАННЫЕ.",
        f"11. Группа «{DEFAULT_BUCKET}» — это НЕ проект, а задачи без доски.",
        f"    НИКОГДА не называй её «проект {DEFAULT_BUCKET}» или «{DEFAULT_BUCKET}».",
        "    Говори о таких задачах как «разрозненные задачи» или «задачи вне проектов».",
        "    В списках «лучший/худший проект» этот бакет не участвует.",
        "",
    ]

    # ── ДАННЫЕ ──
    lines += [
        f"━━━ ДАННЫЕ ЗА НЕДЕЛЮ {data.week_start} — {data.week_end} ━━━",
        "",
        "▸ СВОДКА:",
        f"  Выполнено задач: {data.total_done}",
        f"  Просрочено: {data.total_overdue}",
        f"  В работе (незакрытые): {data.total_in_progress}",
        f"  Общий процент выполнения: {data.overall_rate}%",
        "",
    ]

    # ── ПРОЕКТЫ ──
    lines.append("▸ ПРОЕКТЫ (1 канбан-доска = 1 проект):")
    for p in data.projects:
        if p.name == DEFAULT_BUCKET:
            header = "  ── Задачи вне проектов (НЕ называй это проектом) ──"
        else:
            header = f"  ── Проект «{p.name}» ──"
        lines += [
            "",
            header,
            f"  Выполнено: {p.done_count} | В работе: {p.in_progress_count} | "
            f"Очередь: {p.todo_count} | Просрочено: {p.overdue_count} | "
            f"Процент выполнения: {p.completion_rate}%",
        ]
        if p.done_tasks:
            lines.append("  Выполненные задачи:")
            for t in p.done_tasks:
                lines.append(f"    • {t.fmt()}")
        if p.overdue_tasks:
            lines.append("  Просроченные задачи:")
            for t in p.overdue_tasks:
                lines.append(f"    • {t.fmt()}")
        if p.in_progress_tasks:
            lines.append("  В процессе (незакрытые):")
            for t in p.in_progress_tasks:
                lines.append(f"    • {t.fmt()}")

    # ── ПРИВЫЧКИ ──
    if data.habits:
        lines += ["", "▸ ПРИВЫЧКИ:"]
        for h in data.habits:
            lines.append(f"  {h.grade}  {h.name}: {h.done_days}/7 дней ({h.pct}%)")
    else:
        lines += ["", "▸ ПРИВЫЧКИ: данных нет"]

    # ── ФОРМАТ ОТВЕТА ──
    lines += [
        "",
        "━━━ ФОРМАТ ОТВЕТА ━━━",
        "Напиши полный отчёт с ВСЕМИ семью разделами ниже. Не пропускай ни одного.",
        "Каждая секция — не сплошной абзац, а структура: короткое вступление + буллеты.",
        "",
        "## Вступление",
        "2–3 коротких предложения живым языком от лица друга-наставника на «ты».",
        "Потом буллет-список с **жирными** цифрами — 2–3 наблюдения одной строкой.",
        "",
        "Образец СТИЛЯ (перепиши своими словами с реальными данными):",
        f"  «Неделя закрыта. **{data.total_done}** задач в зачёт, но **{data.total_overdue}** просрочил — не блестяще. Коротко по цифрам:»",
        f"  – **{data.overall_rate}%** выполнения — это общий фон недели.",
        f"  – «**{example_project}**» снова тянет вниз (или вытянул неделю — по данным).",
        f"  – Привычка «**{example_habit}**» закрыта на **{example_habit_pct}%**.",
        "",
        "## Оценка недели",
        "Начни с буллет-списка ключевых метрик (каждая цифра — жирной):",
        f"  – Выполнено: **{data.total_done}** из **{data.total_active}** (**{data.overall_rate}%**)",
        f"  – Просрочено: **{data.total_overdue}**",
        f"  – В работе: **{data.total_in_progress}**",
        "Потом 2–3 предложения интерпретации: что это значит, где перекос.",
        f"Пример интерпретации: «Средняя полоса, **{rate_label}**. Перекос в задачи вне проектов —",
        "  разменял энергию на мелочи.»",
        "",
        "## Разбор по проектам",
        "По КАЖДОМУ проекту из секции ДАННЫЕ — блок вида:",
        "  ### «Имя проекта»",
        "  – Выполнено: **N/M** (**X%**)",
        "  – Просрочено: **K**",
        "  – Ключ: `одно-два предложения — что главное в этом проекте на неделе`.",
        "Группу «задачи вне проектов» тоже разбери отдельным блоком, но НЕ называй её проектом.",
    ]
    if best and worst and best.name != worst.name:
        lines += [
            f"Обязательно укажи лучший проект недели — **«{best.name}»** (**{best.completion_rate}%**) —",
            f"и худший — **«{worst.name}»** (**{worst.completion_rate}%**).",
        ]

    lines += [
        "",
        "## Выполненные задачи",
        "ТОЛЬКО маркированный список, никаких вступительных фраз.",
        "Формат строки: «– **Название задачи** (проект, приоритет)».",
        "Сортируй по приоритету: сначала **СРОЧНЫЙ** и **ВЫСОКИЙ**, потом остальные.",
        "Если задач нет — строка «– Выполненных задач нет».",
        "",
        "## Провалы недели",
        "ТОЛЬКО маркированный список: просроченные задачи + привычки с выполнением **< 50%**.",
        "Формат: «– **Название** — **цифра** (контекст в одно слово)».",
        "Без смягчений, без «в целом». Если провалов нет — «– Провалов нет».",
        "",
        "## 3 совета на следующую неделю",
        "Ровно три совета, нумерованным списком `1.` `2.` `3.`.",
        "Каждый совет — одно КОНКРЕТНОЕ действие со ссылкой на задачу/проект/привычку.",
        "Имена и числа — **жирным**.",
        "Плохой совет: «Старайся больше успевать.» — нет конкретики, запрещено.",
        f"Хороший: «Закрой просроченные задачи из **«{example_project}»** в **понедельник** утром.»",
        f"Ещё: «Подними **«{example_habit}»** до **5/7** — сейчас **{example_habit_pct}%**, это дыра.»",
        "",
        "## Итог",
        "1–2 короткие фразы с главной цифрой недели жирным.",
        "Потом цитата `> ...` — одной фразой главный вывод или установка на следующую неделю.",
        f"Пример: «**{data.overall_rate}%** — это и есть неделя. Делай выводы.»",
        "  `> Следующие 7 дней — не про количество, а про **три приоритета**.`",
        "",
        "━━━ НАПОМИНАНИЕ ━━━",
        "Сейчас напиши полный отчёт. Начни с «## Вступление» и закончи «## Итог».",
        "Все семь разделов обязательны. Минимум 400 слов суммарно.",
        "В каждой секции: жирные числа/имена + хотя бы один список (или цитата в «Итог»).",
    ]

    return "\n".join(lines)
